// Command readme-gen keeps the sample API output of README.md equal to what
// the real handler returns with the fake provider. Run from the repository root.
//
//	go run ./dev/readme-gen          rewrite the block between the markers
//	go run ./dev/readme-gen -check   exit 1 if README.md differs
package main

import (
	"flag"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"net/http/httptest"
	"os"
	"strings"

	"github.com/PaulPerigault/GetUrlCloudRun/internal/api"
	"github.com/PaulPerigault/GetUrlCloudRun/internal/provider/fake"
)

const (
	readme = "README.md"
	begin  = "<!-- BEGIN api-output (generated by `task docs:readme`, do not edit) -->"
	end    = "<!-- END api-output -->"
)

// calls are replayed in order against the real router.
var calls = []string{"/health", "/api/v1/services", "/api/v1/services/hello", "/api/v1/services/absent", "/api/v1/services/Bad_Name"}

func main() {
	check := flag.Bool("check", false, "fail if README.md is not up to date")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "readme-gen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	block, err := render()
	if err != nil {
		return err
	}
	current, err := os.ReadFile(readme)
	if err != nil {
		return err
	}
	updated, err := replaceBlock(string(current), block)
	if err != nil {
		return err
	}
	if check {
		if updated != string(current) {
			return fmt.Errorf("%s is out of date: run `task docs:readme`", readme)
		}
		return nil
	}
	return os.WriteFile(readme, []byte(updated), 0o644) //nolint:gosec // documentation file
}

// render replays the calls against the router backed by the fake provider.
func render() (string, error) {
	p, err := fake.New()
	if err != nil {
		return "", err
	}
	h := api.New(p, slog.New(slog.NewTextHandler(io.Discard, nil)))
	var b strings.Builder
	b.WriteString("```console\n")
	for _, path := range calls {
		rec := httptest.NewRecorder()
		h.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, path, nil))
		fmt.Fprintf(&b, "$ curl -s -w ' [HTTP %%{http_code}]\\n' http://localhost:8080%s\n", path)
		fmt.Fprintf(&b, "%s [HTTP %d]\n", strings.TrimSpace(rec.Body.String()), rec.Code)
	}
	b.WriteString("```")
	return b.String(), nil
}

func replaceBlock(doc, block string) (string, error) {
	i, j := strings.Index(doc, begin), strings.Index(doc, end)
	if i < 0 || j < i {
		return "", fmt.Errorf("markers not found in %s", readme)
	}
	return doc[:i+len(begin)] + "\n" + block + "\n" + doc[j:], nil
}
